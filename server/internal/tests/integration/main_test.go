package integration

import (
	"os"
	"testing"
)

// TestMain 是 Go testing 提供的测试入口。
//
// 它不是某一个具体的 TestCase，
// 而是整个 integration 测试包的生命周期入口。
//
// 执行：
//
//	go test ./tests/integration/...
//
// Go 会先进入 TestMain，
// 然后执行 m.Run()，
// m.Run() 才会真正执行 TestXXX。
func TestMain(m *testing.M) {
	// =========================================================
	// 1. 测试环境初始化
	// =========================================================
	//
	// 后面这里会放：
	//
	// - 加载 test 配置
	// - 初始化 MySQL
	// - 初始化 Redis
	// - 初始化 Casbin
	// - 初始化 Logger
	// - 初始化测试 Application
	//
	// 当前先不做复杂初始化。
	// =========================================================

	exitCode := m.Run()

	// =========================================================
	// 2. 测试结束
	// =========================================================
	//
	// 后面可以在这里统一关闭：
	//
	// - MySQL
	// - Redis
	// - 其他资源
	//
	// exitCode 非 0 说明测试失败。
	// =========================================================

	os.Exit(exitCode)
}
