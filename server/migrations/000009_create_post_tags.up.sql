-- =========================================================
-- 创建文章与标签关联表
-- =========================================================
--
-- 这是一张“中间表”。
--
-- 用来表达：
--
-- Post ←→ Tag
--
-- 的多对多关系。
-- =========================================================

CREATE TABLE IF NOT EXISTS post_tags (
    -- -----------------------------------------------------
    -- 文章 ID
    -- -----------------------------------------------------
    post_id CHAR(26) NOT NULL,
    -- -----------------------------------------------------
    -- 标签 ID
    -- -----------------------------------------------------
    tag_id CHAR(26) NOT NULL,
    -- -----------------------------------------------------
    -- 复合主键
    -- -----------------------------------------------------
    --
    -- 一篇文章 + 一个标签
    -- 只能出现一次。
    --
    -- 例如：
    --
    -- post A + Vue3
    --
    -- 不能重复两次。
    -- -----------------------------------------------------
    PRIMARY KEY (post_id, tag_id),
    -- -----------------------------------------------------
    -- post_id 索引
    -- -----------------------------------------------------
    --
    -- 查询：
    --
    -- “这篇文章有哪些 Tag？”
    --
    -- 会使用这个索引。
    -- -----------------------------------------------------
    KEY idx_post_tags_post_id (post_id),
    -- -----------------------------------------------------
    -- tag_id 索引
    -- -----------------------------------------------------
    --
    -- 查询：
    --
    -- “这个 Tag 下有哪些文章？”
    --
    -- 会使用这个索引。
    -- -----------------------------------------------------
    KEY idx_post_tags_tag_id (tag_id),
    -- -----------------------------------------------------
    -- 外键：文章
    -- -----------------------------------------------------
    CONSTRAINT fk_post_tags_post
        FOREIGN KEY (post_id)
        REFERENCES posts(id)
        ON DELETE CASCADE,
    -- -----------------------------------------------------
    -- 外键：标签
    -- -----------------------------------------------------
    CONSTRAINT fk_post_tags_tag
        FOREIGN KEY (tag_id)
        REFERENCES tags(id)
        ON DELETE CASCADE
) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
  COLLATE=utf8mb4_unicode_ci
  COMMENT='文章与标签关联表';
